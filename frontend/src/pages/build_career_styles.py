"""
Generate the per-page stylesheets from CareerShared.css.

The three new pages (Find Jobs, Skill Passport, Application Tracker)
share one design system but each had grown its own class prefix
(fj-, sp-, ap-). Rather than duplicate the shared rules three times
by hand, or rename every class in the JSX, this rewrites the shared
sheet once per prefix.

Run:  python build_career_styles.py
"""

import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SHARED = os.path.join(HERE, "CareerShared.css")

# prefix -> (output file, page-specific rules appended after it)
PAGES = {
    "fj": ("FindJobs.css", """
/* Find Jobs specific */
.fj-section-head { display: flex; flex-wrap: wrap; gap: 14px;
  align-items: center; justify-content: space-between; }
.fj-section-head .fj-card-title { margin: 0; }
"""),
    "sp": ("SkillPassport.css", """
/* Skill Passport specific */
.sp-bullets { margin: 12px 0 0; padding: 0; list-style: none; }
.sp-bullets li { padding: 12px 0; border-top: 1px solid #eef0f6; }
.sp-bullets strong { display: block; margin-bottom: 5px; font-size: 14px; }
.sp-bullets p { margin: 0 0 4px; font-size: 13.5px; line-height: 1.6;
  color: #4a536b; }
"""),
    "ap": ("Applications.css", """
/* Application Tracker specific */
.ap-next { margin: 7px 0 0; font-size: 13px; font-weight: 600; color: #8a5a10; }
.ap-entry-links { display: flex; flex-wrap: wrap; gap: 12px; align-items: center;
  margin-top: 8px; }
.ap-entry-links a, .ap-link-btn { font-size: 12.5px; font-weight: 600;
  color: #3155d9; text-decoration: none; background: none; border: none;
  padding: 0; cursor: pointer; font-family: inherit; }
.ap-entry-links a:hover, .ap-link-btn:hover { text-decoration: underline; }
.ap-history { margin: 12px 0 0; padding: 0 0 0 18px; }
.ap-history li { padding: 6px 0; font-size: 12.5px; color: #6b7385; }
.ap-history strong { color: #1f2430; }
.ap-history span { margin-left: 8px; }
.ap-history p { margin: 3px 0 0; font-size: 12.5px; }
.ap-entry-side select { padding: 7px 9px; font-family: inherit; font-size: 12.5px;
  color: #1f2430; background: #fff; border: 1px solid #d7dcea; border-radius: 7px; }
.ap-status { padding: 3px 10px; font-size: 11px; font-weight: 700;
  border-radius: 999px; }
.ap-status-interested { color: #3c4457; background: #eef1f7; }
.ap-status-preparing { color: #8a5a10; background: #fdf3e2; }
.ap-status-applied { color: #1c3f8a; background: #e5ecfd; }
.ap-status-assessment { color: #5b21b6; background: #f0e8fd; }
.ap-status-interview { color: #0f5e6e; background: #e2f4f7; }
.ap-status-offer { color: #1c5c3a; background: #e6f5ed; }
.ap-status-rejected { color: #b4232b; background: #fdecec; }
"""),
}


def main():
    with io.open(SHARED, encoding="utf-8") as handle:
        shared = handle.read()

    header = (
        "/* Generated by build_career_styles.py - do not edit by hand.\n"
        "   Shared rules from CareerShared.css, rewritten for the %s\n"
        "   class prefix. Change CareerShared.css and re-run instead. */\n\n"
    )

    for prefix, (filename, extra) in PAGES.items():
        # Only the class prefix is rewritten. Comment text mentioning
        # "cp-page" style names is left alone, so the note stays readable.
        body = shared.replace(".cp-", "." + prefix + "-")

        content = header % prefix + body

        if extra:
            content += "\n" + extra.strip() + "\n"

        target = os.path.join(HERE, filename)

        with io.open(target, "w", encoding="utf-8", newline="\n") as out:
            out.write(content)

        print(f"wrote {filename:<22} {len(content):>6} bytes")


if __name__ == "__main__":
    main()
