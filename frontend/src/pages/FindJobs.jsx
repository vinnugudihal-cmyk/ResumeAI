import { useEffect, useState } from "react";
import { Link, useNavigate } from "react-router-dom";
import {
  searchJobs,
  fetchJobMeta,
  fetchSavedJobs,
  saveJob,
  deleteSavedJob,
  createMyResume,
} from "../services/api";
import "./FindJobs.css";

/**
 * Find Jobs, and the jobs you kept.
 *
 * ResumeAI has no job board. What a search shows depends on whether
 * a provider is configured:
 *
 *   api      real listings from that provider
 *   external real search links built from these filters
 *
 * The mode is always stated on the page. No listing, company,
 * salary or link here is ever generated by ResumeAI.
 *
 * ``initialTab`` lets /saved-jobs open straight to the saved list.
 * It is the same component, not a second implementation.
 */

const WORK_MODES = [
  { value: "any", label: "Any" },
  { value: "remote", label: "Remote" },
  { value: "hybrid", label: "Hybrid" },
  { value: "onsite", label: "On-site" },
];

// Employment type and experience level are different questions, so
// they get their own dropdowns. Merging them meant "full-time
// entry-level", the most common student search, was unreachable.
const EMPLOYMENT_TYPES = [
  { value: "", label: "Any type" },
  { value: "full_time", label: "Full time" },
  { value: "part_time", label: "Part time" },
  { value: "internship", label: "Internship" },
  { value: "contract", label: "Contract" },
  { value: "temporary", label: "Temporary" },
];

const EXPERIENCE_LEVELS = [
  { value: "any", label: "Any level" },
  { value: "entry_level", label: "Entry level / fresher" },
  { value: "mid_level", label: "Mid level" },
  { value: "senior_level", label: "Senior level" },
];

const EMPTY_FILTERS = {
  keywords: "",
  title: "",
  location: "",
  work_mode: "any",
  employment: "",
  experience: "any",
};

/**
 * A readable sentence for the filters the server actually applied.
 * Built from the response, not from what was typed, so a value the
 * server corrected is reported as corrected.
 */
function describeFilters(applied) {
  if (!applied) return "your search";

  const words = [];

  // The role and the keywords are two different things, and this
  // used to splice them into one quoted phrase: typing "data
  // analyst, python" as keywords with "Data Analyst" as the role
  // displayed "data analyst, python Data Analyst", which reads as
  // a single mangled search term. They are now labelled separately
  // - which is also how the job boards actually receive them.
  const role = (applied.title || "").trim();
  const extra = (applied.keywords || "").trim();

  if (role && extra) {
    words.push(`${role} (keywords: ${extra})`);
  } else if (role) {
    words.push(role);
  } else if (extra) {
    words.push(extra);
  }

  if (applied.location) words.push(`in ${applied.location}`);

  const workMode = WORK_MODES.find(
    (item) => item.value === applied.work_mode
  );

  if (workMode && applied.work_mode !== "any") {
    words.push(workMode.label.toLowerCase());
  }

  const employment = EMPLOYMENT_TYPES.find(
    (item) => item.value === applied.employment
  );

  if (employment) words.push(employment.label.toLowerCase());

  const experience = EXPERIENCE_LEVELS.find(
    (item) => item.value === applied.experience
  );

  if (experience && applied.experience !== "any") {
    words.push(experience.label.toLowerCase());
  }

  return words.length ? words.join(", ") : "everything";
}

export default function FindJobs({ initialTab = "search" }) {
  const navigate = useNavigate();

  const [tab, setTab] = useState(initialTab === "saved" ? "saved" : "search");

  const [meta, setMeta] = useState(null);
  const [filters, setFilters] = useState(EMPTY_FILTERS);
  const [result, setResult] = useState(null);
  const [searching, setSearching] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  const [saved, setSaved] = useState([]);
  const [savingId, setSavingId] = useState(0);
  const [busyJob, setBusyJob] = useState(0);

  const [draft, setDraft] = useState(null);

  useEffect(() => {
    let cancelled = false;

    fetchJobMeta()
      .then((data) => {
        if (!cancelled) setMeta(data);
      })
      .catch(() => {
        /* the form still works without the city list */
      });

    fetchSavedJobs()
      .then((list) => {
        if (!cancelled) setSaved(list);
      })
      .catch(() => {
        /* an empty list is fine */
      });

    return () => {
      cancelled = true;
    };
  }, []);

  useEffect(() => {
    if (!notice) return undefined;
    const timer = setTimeout(() => setNotice(""), 4000);
    return () => clearTimeout(timer);
  }, [notice]);

  function setFilter(name, value) {
    setFilters((previous) => ({ ...previous, [name]: value }));
  }

  async function handleSearch(event) {
    event.preventDefault();

    setSearching(true);
    setError("");
    setResult(null);

    try {
      const data = await searchJobs(filters);
      setResult(data);
    } catch (err) {
      setError(
        err?.message || "Search is unavailable right now."
      );
    } finally {
      setSearching(false);
    }
  }

  function startSave(listing) {
    setDraft({
      title: listing.title,
      company: listing.company || "",
      location: listing.location || "",
      employment: listing.employment || "",
      salary:
        listing.salary_min || listing.salary_max
          ? `${listing.salary_currency || ""} ${listing.salary_min ?? 0} - ${listing.salary_max ?? 0}`
          : "",
      url: listing.url || "",
      source: listing.source || "api",
      description: listing.description || "",
      posted_on: listing.posted_on || "",
    });
  }

  function startManualSave() {
    // Needed because, with no provider configured, there are no
    // listings to save from. The user can still paste in a job they
    // found on a real site, which is the normal path in this mode.
    setDraft({
      title: "",
      company: "",
      location: "",
      employment: "",
      salary: "",
      url: "",
      source: "external_link",
      description: "",
      posted_on: "",
    });
  }

  async function handleSaveJob(event) {
    event.preventDefault();

    setSavingId(1);
    setError("");

    try {
      const job = await saveJob(draft);
      setSaved((previous) => [job, ...previous]);
      setDraft(null);
      setNotice("Job saved to your list.");
    } catch (err) {
      setError(err?.message || "Could not save that job.");
    } finally {
      setSavingId(0);
    }
  }

  async function handleDelete(id) {

    if (!window.confirm("Remove this saved job?")) return;

    try {
      await deleteSavedJob(id);
      setSaved((previous) => previous.filter((j) => j.id !== id));
    } catch (err) {
      setError(err?.message || "Could not remove that job.");
    }
  }

  /**
   * Carry the job into the application tracker.
   *
   * This used to be a plain link to /applications, which dropped the
   * user on a blank form with none of the job details. Now the job
   * travels with the navigation and the form opens filled in.
   */
  function trackApplication(job) {
    navigate("/applications", {
      state: {
        prefill: {
          company: job.company || "",
          role: job.title || "",
          job_url: job.url || "",
          saved_job_id: job.id,
        },
      },
    });
  }

  /**
   * Send the job's own description to the matcher.
   *
   * The text comes from the listing that was saved. It is not
   * written here, and an empty description simply opens the matcher
   * blank rather than inventing a role.
   */
  function matchJob(job) {
    if (!job.description) {
      setError(
        "This saved job has no description text, so there is "
        + "nothing to compare against. Open Job match and paste the "
        + "requirements there."
      );
      return;
    }

    navigate("/job-match", {
      state: {
        prefill: {
          savedJobId: job.id,
          title: job.title || "",
          company: job.company || "",
          url: job.url || "",
          description: job.description,
        },
      },
    });
  }

  /**
   * Start a resume for this job, seeded from the Career Profile.
   *
   * Everything in it is the user's own data. If they have not filled
   * in their profile yet, the resume opens genuinely empty rather
   * than full of a fictional person.
   */
  async function tailorResume(job) {
    setBusyJob(job.id);
    setError("");

    try {
      const created = await createMyResume({
        title: `${job.title} — ${job.company || "application"}`,
        targetRole: job.title || "",
        fromProfile: true,
      });

      if (created) {
        navigate(`/resume-builder/${created.id}`);
      }
    } catch (err) {
      setError(err?.message || "Could not start that resume.");
    } finally {
      setBusyJob(0);
    }
  }

  const mode = result?.mode;

  return (
    <div className="fj-page">
      <header className="fj-header">
        <div>
          <Link to="/dashboard" className="fj-back">
            ← Back to dashboard
          </Link>
          <h1>Find Jobs</h1>
          <p className="fj-sub">
            Search with your filters, then open a real job board to
            see the actual openings. ResumeAI does not host jobs and
            never invents one.
          </p>
        </div>
      </header>

      {notice && (
        <div className="fj-notice" role="status">
          {notice}
        </div>
      )}
      {error && (
        <div className="fj-notice fj-notice-error" role="alert">
          {error}
        </div>
      )}

      {/* ---------- search / saved tabs ---------- */}
      <div className="fj-tabs" role="tablist" aria-label="Jobs">
        <button
          type="button"
          role="tab"
          aria-selected={tab === "search"}
          className={`fj-tab ${tab === "search" ? "active" : ""}`}
          onClick={() => setTab("search")}
        >
          Search jobs
        </button>
        <button
          type="button"
          role="tab"
          aria-selected={tab === "saved"}
          className={`fj-tab ${tab === "saved" ? "active" : ""}`}
          onClick={() => setTab("saved")}
        >
          Saved jobs ({saved.length})
        </button>
      </div>

      {tab === "search" && (
      <>
      {/* ---------- search form ---------- */}
      <form className="fj-card" onSubmit={handleSearch}>
        <div className="fj-grid">
          <label className="fj-field">
            <span>Keywords</span>
            <input
              type="text"
              placeholder="python, data analyst…"
              value={filters.keywords}
              onChange={(event) =>
                setFilter("keywords", event.target.value)
              }
            />
          </label>

          <label className="fj-field">
            <span>Job title</span>
            <input
              type="text"
              placeholder="Backend Developer"
              value={filters.title}
              onChange={(event) =>
                setFilter("title", event.target.value)
              }
            />
          </label>

          <label className="fj-field">
            <span>Location</span>
            <input
              type="text"
              list="fj-cities"
              placeholder="Bengaluru"
              value={filters.location}
              onChange={(event) =>
                setFilter("location", event.target.value)
              }
            />
            <datalist id="fj-cities">
              {(meta?.cities || []).map((city) => (
                <option key={city} value={city} />
              ))}
            </datalist>
          </label>

          <label className="fj-field">
            <span>Work arrangement</span>
            <select
              value={filters.work_mode}
              onChange={(event) =>
                setFilter("work_mode", event.target.value)
              }
            >
              {WORK_MODES.map((mode_) => (
                <option key={mode_.value} value={mode_.value}>
                  {mode_.label}
                </option>
              ))}
            </select>
          </label>

          <label className="fj-field">
            <span>Employment type</span>
            <select
              value={filters.employment}
              onChange={(event) =>
                setFilter("employment", event.target.value)
              }
            >
              {EMPLOYMENT_TYPES.map((item) => (
                <option key={item.value} value={item.value}>
                  {item.label}
                </option>
              ))}
            </select>
          </label>

          <label className="fj-field">
            <span>Experience level</span>
            <select
              value={filters.experience}
              onChange={(event) =>
                setFilter("experience", event.target.value)
              }
            >
              {EXPERIENCE_LEVELS.map((item) => (
                <option key={item.value} value={item.value}>
                  {item.label}
                </option>
              ))}
            </select>
          </label>
        </div>

        <div className="fj-actions">
          <button type="submit" className="fj-btn" disabled={searching}>
            {searching ? "Searching…" : "Search jobs"}
          </button>
          <button
            type="button"
            className="fj-btn fj-btn-ghost"
            onClick={() => {
              setFilters(EMPTY_FILTERS);
              setResult(null);
            }}
          >
            Clear
          </button>
          <button
            type="button"
            className="fj-btn fj-btn-ghost"
            onClick={() => setTab("saved")}
          >
            Go to saved ({saved.length})
          </button>
        </div>
      </form>

      {/* ---------- results ---------- */}
      {result && (
        <section className="fj-card">
          <div className={`fj-mode fj-mode-${mode}`}>
            {mode === "api" ? (
              <>
                <strong>Live listings</strong>
                <p>{result.notice}</p>
              </>
            ) : (
              <>
                <strong>
                  Search links, not listings
                </strong>
                <p>{result.notice}</p>
              </>
            )}
          </div>

          {result.setup?.needed && (
            /* Environment variable names and file paths are an
               administrator's concern, not something a person
               looking for a job should be shown. They used to be
               rendered here as raw setup instructions. */
            <p className="fj-setup">
              Live listings need a job data service to be connected
              by whoever runs this installation. Until that is
              done, the links below go straight to the job sites
              themselves, so you can still search and apply.
            </p>
          )}

          {/* What was actually searched, after the server cleaned
              the values. An unrecognised option is corrected and
              shown here rather than quietly dropped. */}
          <p className="fj-applied">
            Searching for: {describeFilters(result.filters)}
          </p>

          {mode === "api" && result.listings.length === 0 && (
            <p className="fj-empty">
              The provider answered but found nothing for that
              search. Try fewer keywords or a different location.
            </p>
          )}

          {mode === "api" && result.listings.length > 0 && (
            <div className="fj-results">
              {result.listings.map((listing, index) => (
                <article
                  key={`${listing.url}-${index}`}
                  className="fj-result"
                >
                  <h2 className="fj-result-title">
                    {listing.url ? (
                      <a
                        href={listing.url}
                        target="_blank"
                        rel="noreferrer noreferrer"
                      >
                        {listing.title} ↗
                      </a>
                    ) : (
                      listing.title
                    )}
                  </h2>
                  <p className="fj-result-meta">
                    {[listing.company, listing.location]
                      .filter(Boolean)
                      .join(" · ")}
                    {listing.posted_on && ` · ${listing.posted_on}`}
                  </p>
                  {listing.description && (
                    <p className="fj-result-desc">
                      {listing.description.slice(0, 260)}
                      {listing.description.length > 260 && "…"}
                    </p>
                  )}
                  <button
                    type="button"
                    className="fj-btn fj-btn-small"
                    onClick={() => startSave(listing)}
                  >
                    Save this job
                  </button>
                </article>
              ))}
            </div>
          )}

          {result.links?.length > 0 && (
            <>
              <h3 className="fj-sub-title">
                Open a real job board with this search
              </h3>
              <div className="fj-links">
                {result.links.map((link) => (
                  <a
                    key={link.key}
                    className="fj-link"
                    href={link.url}
                    target="_blank"
                    rel="noreferrer noreferrer"
                  >
                    <strong>{link.label} ↗</strong>
                    <span>{link.note}</span>
                  </a>
                ))}
              </div>
            </>
          )}
        </section>
      )}

      </>
      )}

      {/* ---------- saved jobs ---------- */}
      {tab === "saved" && (
      <section className="fj-card">
        <div className="fj-section-head">
          <h2 className="fj-card-title">
            Saved jobs{" "}
            <span className="fj-count">{saved.length}</span>
          </h2>
          {!draft && (
            <button
              type="button"
              className="fj-btn fj-btn-small fj-btn-ghost"
              onClick={startManualSave}
            >
              + Save a job you found
            </button>
          )}
        </div>

        {saved.length === 0 ? (
          <p className="fj-empty">
            Nothing saved yet. Switch to{" "}
            <button
              type="button"
              className="fj-linkbtn"
              onClick={() => setTab("search")}
            >
              Search jobs
            </button>{" "}
            then save anything worth coming back to.
          </p>
        ) : (
          <ul className="fj-saved">
            {saved.map((job) => (
              <li key={job.id} className="fj-saved-item">
                <div className="fj-saved-main">
                  <strong>{job.title}</strong>
                  <span className="fj-saved-meta">
                    {[job.company, job.location]
                      .filter(Boolean)
                      .join(" · ")}
                  </span>
                  {job.url && (
                    <a
                      className="fj-saved-link"
                      href={job.url}
                      target="_blank"
                      rel="noreferrer noreferrer"
                    >
                      Open listing ↗
                    </a>
                  )}
                </div>

                {/*
                  Each of these carries the job across to a feature
                  that can actually use it, rather than being a link
                  that drops the user on an unrelated blank page.
                */}
                <div className="fj-saved-actions">
                  <button
                    type="button"
                    className="fj-btn fj-btn-small"
                    onClick={() => trackApplication(job)}
                  >
                    Track application
                  </button>

                  <button
                    type="button"
                    className="fj-btn fj-btn-small fj-btn-ghost"
                    onClick={() => tailorResume(job)}
                    disabled={busyJob === job.id}
                  >
                    {busyJob === job.id
                      ? "Starting…"
                      : "Tailor a resume"}
                  </button>

                  <button
                    type="button"
                    className="fj-btn fj-btn-small fj-btn-ghost"
                    onClick={() => matchJob(job)}
                  >
                    Match my skills
                  </button>

                  <Link
                    to="/career-mission"
                    className="fj-btn fj-btn-small fj-btn-ghost"
                  >
                    Career Mission
                  </Link>

                  <button
                    type="button"
                    className="fj-btn fj-btn-small fj-btn-danger"
                    onClick={() => handleDelete(job.id)}
                  >
                    Remove
                  </button>
                </div>
              </li>
            ))}
          </ul>
        )}
      </section>
      )}
      {/* ---------- save form ---------- */}
      {draft && (
        <form className="fj-card" onSubmit={handleSaveJob}>
          <h2 className="fj-card-title">Save this job</h2>
          <p className="fj-hint">
            Saved to your account so you can come back to it and
            track your application.
          </p>

          <div className="fj-grid">
            <label className="fj-field">
              <span>Job title *</span>
              <input
                type="text"
                required
                value={draft.title}
                onChange={(event) =>
                  setDraft({ ...draft, title: event.target.value })
                }
              />
            </label>
            <label className="fj-field">
              <span>Company</span>
              <input
                type="text"
                value={draft.company}
                onChange={(event) =>
                  setDraft({ ...draft, company: event.target.value })
                }
              />
            </label>
            <label className="fj-field fj-field-wide">
              <span>Link *</span>
              <input
                type="url"
                required
                placeholder="https://…"
                value={draft.url}
                onChange={(event) =>
                  setDraft({ ...draft, url: event.target.value })
                }
              />
            </label>
            <label className="fj-field">
              <span>Location</span>
              <input
                type="text"
                value={draft.location}
                onChange={(event) =>
                  setDraft({ ...draft, location: event.target.value })
                }
              />
            </label>
            <label className="fj-field">
              <span>Salary (only if the listing states it)</span>
              <input
                type="text"
                placeholder="Leave blank if not stated"
                value={draft.salary}
                onChange={(event) =>
                  setDraft({ ...draft, salary: event.target.value })
                }
              />
            </label>
            <label className="fj-field fj-field-wide">
              <span>Job description (optional)</span>
              <textarea
                rows={6}
                placeholder="Paste the requirements from the listing so Job match can compare them with what you have actually done."
                value={draft.description}
                onChange={(event) =>
                  setDraft({ ...draft, description: event.target.value })
                }
              />
            </label>
          </div>

          <div className="fj-actions">
            <button
              type="submit"
              className="fj-btn"
              disabled={savingId === 1}
            >
              {savingId === 1 ? "Saving…" : "Save job"}
            </button>
            <button
              type="button"
              className="fj-btn fj-btn-ghost"
              onClick={() => setDraft(null)}
            >
              Cancel
            </button>
          </div>
        </form>
      )}
    </div>
  );
}
